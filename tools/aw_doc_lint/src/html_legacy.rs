//! HTML5 named character references that the tokenizer accepts without `;`.
//!
//! The WHATWG table lists these 106 names both with and without a trailing
//! semicolon. Lookup is case-sensitive and longest-match. A semicolon form is
//! resolved first, by `html_entities`, so this table is only the legacy set.

pub(crate) fn legacy_match(bytes: &[u8]) -> Option<(&'static str, usize)> {
    let mut best = None;
    let mut len = 0;
    let max = bytes.len().min(32);
    while len < max && bytes[len].is_ascii_alphanumeric() {
        len += 1;
        let Ok(candidate) = std::str::from_utf8(&bytes[..len]) else {
            break;
        };
        if let Ok(idx) = LEGACY.binary_search_by(|row| row.0.cmp(candidate)) {
            best = Some((LEGACY[idx].1, len));
        }
    }
    best
}

